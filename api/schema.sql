CREATE TABLE IF NOT EXISTS users(
  u TEXT PRIMARY KEY, name TEXT NOT NULL, phone TEXT, role TEXT NOT NULL CHECK(role IN('driver','admin')),
  pw_hash TEXT NOT NULL, pw_salt TEXT NOT NULL, bus TEXT, active INTEGER NOT NULL DEFAULT 1, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS buses(id TEXT PRIMARY KEY, label TEXT, active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS shifts(
  id INTEGER PRIMARY KEY AUTOINCREMENT, u TEXT NOT NULL, bus TEXT NOT NULL, start_ts INTEGER NOT NULL, end_ts INTEGER,
  km REAL NOT NULL DEFAULT 0, trips INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS shifts_u ON shifts(u,start_ts);
CREATE TABLE IF NOT EXISTS positions(
  u TEXT PRIMARY KEY, lat REAL, lon REAL, speed REAL, acc REAL, bat INTEGER, ts INTEGER NOT NULL,
  moving INTEGER NOT NULL DEFAULT 0, still_ms INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS login_fail(k TEXT PRIMARY KEY, n INTEGER NOT NULL, ts INTEGER NOT NULL);
